/**
 * Build the aggregation worker as a standalone script in `public/`.
 *
 * Why not `new Worker(new URL('./worker.ts', import.meta.url))`: under
 * `output: 'export'` the Turbopack build copies that file into
 * `_next/static/media/ledger.worker.<hash>.ts` — the TypeScript *source*, not a
 * compiled script — so the browser fetches a `.ts` and the worker never runs.
 * That failure is invisible in `pnpm dev` and only appears in the built output,
 * so the worker is bundled by esbuild from the same source the tests cover, and
 * the file it writes is generated, not committed.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";

import { build } from "esbuild";

const root = resolve(import.meta.dirname, "..");
const entry = resolve(root, "workers/ledger.worker.ts");
const outfile = resolve(root, "public/ledger.worker.js");

await mkdir(dirname(outfile), { recursive: true });

const result = await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: true,
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
});

await writeFile(
  outfile,
  `/* Generated by scripts/build-worker.mjs from workers/ledger.worker.ts — do not edit. */\n${await readFile(outfile, "utf8")}`,
);

const bytes = (await readFile(outfile)).byteLength;
const inputs = Object.keys(result.metafile?.inputs ?? {});
process.stdout.write(
  `worker: public/ledger.worker.js ${bytes} B from ${inputs.length} module(s)\n`,
);
